"""Перевірка логіки (ПР4): стани будинку, яких не повинно бути після виведення.

Кожна перевірка – це суперечність. Частину з них система може отримати
«у спадок» від користувача (наприклад, він сам відчинив вікно), тому для
перевірок з caused=True порушенням вважається лише випадок, коли система
сама змінила хоча б один з фактів, що беруть участь у суперечності.
"""
from dataclasses import dataclass


@dataclass
class Check:
    code: str
    text: str
    keys: tuple          # факти, які беруть участь
    test: object         # функція f(facts) -> True, якщо є суперечність
    caused: bool         # True – рахувати, лише якщо систему щось змінила


def _g(f, k):
    return f.get(k)


CHECKS = [
    Check("К1", "кондиціонер охолоджує при відкритих вікнах",
          ("Вікна.стан", "Кондиціонер.режим"),
          lambda f: _g(f, "Вікна.стан") == "відкрито" and _g(f, "Кондиціонер.режим") == "помірне_охолодження",
          True),
    Check("К2", "обігрівач працює при відкритих вікнах",
          ("Вікна.стан", "Обігрівач.стан"),
          lambda f: _g(f, "Вікна.стан") == "відкрито" and _g(f, "Обігрівач.стан") == "увімкнено",
          True),
    Check("К3", "вікна відкриті навесні, коли вдома алергік",
          ("Вікна.стан",),
          lambda f: (_g(f, "Вікна.стан") == "відкрито" and _g(f, "Середовище.пора_року") == "весна"
                     and _g(f, "Мешканці.є_алергік") == "так"),
          True),
    Check("К4", "економний режим, коли мешканець удома",
          ("Режим.назва",),
          lambda f: _g(f, "Режим.назва") == "економний" and _g(f, "Мешканці.є_люди") == "так",
          False),
    Check("К5", "криза без причини (немає ні обстрілу, ні забруднення)",
          ("Режим.криза",),
          lambda f: (_g(f, "Режим.криза") == "так" and _g(f, "Середовище.обстріл") == "ні"
                     and (_g(f, "Середовище.індекс_забруднення") or 0) <= 100),
          False),
    Check("К6", "вікна ізольовані, хоча кризи немає",
          ("Вікна.стан",),
          lambda f: _g(f, "Вікна.стан") == "закрито_ізоляція" and _g(f, "Режим.криза") == "ні",
          False),
    Check("К7", "пристрої працюють від зарядної станції",
          ("Кондиціонер.режим", "Обігрівач.стан", "Очищувач.режим", "Тепла_підлога.потужність", "Поїлка.стан"),
          lambda f: _g(f, "Живлення.джерело") == "зарядна_станція" and (
              _g(f, "Кондиціонер.режим") not in (None, "вимкнено") or _g(f, "Обігрівач.стан") == "увімкнено"
              or _g(f, "Очищувач.режим") not in (None, "вимкнено")
              or _g(f, "Тепла_підлога.потужність") not in (None, "вимкнено") or _g(f, "Поїлка.стан") == "увімкнено"),
          False),
    Check("К8", "сигналізація спрацювала, коли мешканець удома",
          ("Сигналізація.стан",),
          lambda f: _g(f, "Сигналізація.стан") == "тривога" and _g(f, "Мешканці.є_люди") == "так",
          False),
]


def violations(before, after):
    """Список перевірок, які порушено. before/after – словники фактів до і після виведення."""
    found = []
    for c in CHECKS:
        if not c.test(after):
            continue
        if c.caused and all(before.get(k) == after.get(k) for k in c.keys):
            continue
        found.append(c)
    return found
