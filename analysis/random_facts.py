"""Генератор випадкових ситуацій для перевірки бази правил (ПР4).

Кожна ситуація – це випадкові покази датчиків і випадковий стан будинку
(режим, криза, вікна), з якого система має прийти до розумного стану.
"""
import random

SEASONS = ["зима", "весна", "літо", "осінь"]


def random_facts(rng: random.Random):
    pick = rng.choice
    f = [
        ("Кімната", "температура", rng.randint(12, 32)),
        ("Кімната", "вологість", rng.randint(25, 85)),
        ("Кімната", "рівень_CO2", rng.choice([500, 700, 900, 1100, 1300, 1600])),
        ("Картка", "вставлена", pick(["так", "ні"])),
        ("Датчик_руху", "рух", pick(["так", "ні"])),
        ("Мешканці", "є_тварини", pick(["так", "ні"])),
        ("Мешканці", "є_алергік", pick(["так", "ні"])),
        ("Середовище", "пора_року", pick(SEASONS)),
        ("Середовище", "опади", pick(["немає", "немає", "дощ", "сніг"])),
        ("Середовище", "індекс_забруднення", rng.choice([30, 60, 90, 120, 160])),
        ("Середовище", "обстріл", "так" if rng.random() < 0.15 else "ні"),
        ("Живлення", "джерело", "зарядна_станція" if rng.random() < 0.15 else "мережа"),
        # стан будинку, що лишився з попереднього разу
        ("Режим", "назва", pick(["комфортний", "економний", "сон", "ізольований"])),
        ("Режим", "криза", pick(["ні", "ні", "так"])),
        ("Вікна", "стан", pick(["закрито", "закрито", "відкрито", "закрито_ізоляція"])),
    ]
    return [{"object": o, "attribute": a, "value": v} for o, a, v in f]
